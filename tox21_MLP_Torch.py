import	deepchem	as	dc

# loads the Tox21 dataset
# featurizer='ECFP' converts each molecule's structure into an Extended-Connectivity Fingerprint,
# which is represented as a 1024-bit vector of 1s and 0s
tasks, datasets, transformers =	dc.molnet.load_tox21(featurizer='ECFP')
train_dataset, valid_dataset, test_dataset = datasets

print(train_dataset)

# initializes a deep neural network
# output 12 separate binary predictions per molecule.
# n_features=1024 matches the 1024 bits generated by the ECFP featurizer.
# uses a single hidden layer containing 1000 neurons
model	=	dc.models.MultitaskClassifier(n_tasks=12,	n_features=1024,	layer_sizes=[1000])

# trains the neural network on the train_dataset for 10 epochs.
model.fit(train_dataset,	nb_epoch=10)
metric	=	dc.metrics.Metric(dc.metrics.roc_auc_score)

print('training	set	score:',	model.evaluate(train_dataset,	[metric],	transformers))
print('test	set	score:',	model.evaluate(test_dataset,	[metric],	transformers))